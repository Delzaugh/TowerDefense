import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,readFile,readdir} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {hash} from './contracts.mjs';
import {reviewAsset} from './visual-review.mjs';

// Isolated evidence fixtures test identity/status behavior, not artistic quality.
const root=await mkdtemp(path.join(os.tmpdir(),'tower-review-'));
const folder='blender/environment/review_fixture/v01', validation=folder+'/validation';
await mkdir(path.join(root,validation),{recursive:true});
await mkdir(path.join(root,'assets/runtime/environment'),{recursive:true});
const source=folder+'/review_fixture_v01.blend', runtime='assets/runtime/environment/review_fixture_v01.glb';
const put=async(file,value)=>writeFile(path.join(root,file),typeof value==='string'?value:JSON.stringify(value));
const image=validation+'/front.png';
await put(source,'editable source');await put(runtime,'runtime geometry');await put(image,'captured pixels');
const identity={asset:'review_fixture',version:'v01',revision:1,sha256:hash(Buffer.from('runtime geometry')),sourceHash:hash(Buffer.from('editable source'))};
const item={manifest:folder+'/asset.json',data:{id:identity.asset,version:'v01',revision:1,source:{path:source},runtime,clips:[],delivery:{sha256:identity.sha256,sourceHash:identity.sourceHash}}};
await put(validation+'/report.json',{...identity,passed:true,errors:[]});
await put(validation+'/render_evidence.json',{sha256:identity.sha256,views:[{file:'front.png',view:'front',mode:'shaded',sha256:hash(Buffer.from('captured pixels'))}]});
const run=options=>reviewAsset(item,{root,...options});
assert.equal((await run()).ready,false);
assert.equal((await run({initialize:true})).initialized,true);
let record=JSON.parse(await readFile(path.join(root,validation,'visual_review.json'),'utf8'));
assert.equal(record.userAcceptance.status,'pending');assert.equal((await run()).ready,false);
record.reviewedAt=new Date().toISOString();
for(const key of ['referenceFidelity','construction','readability'])record.checks[key]={status:'passed',findings:'Inspected the scoped shape and attachments against the fixture reference.'};
record.secondPass={status:'passed',findings:'Reopened the finished export and checked the affected view after repairs.'};
const save=()=>put(validation+'/visual_review.json',record);
await save();assert.equal((await run()).ready,true,'User approval is not an author-review gate');
assert.equal((await run({initialize:true})).initialized,false,'Do not overwrite a current assessment');
record.userAcceptance={status:'rejected',note:'The user rejected the proportions.'};await save();
assert.equal((await run()).ready,false,'User rejection supersedes an author pass');
record.userAcceptance={status:'accepted',note:'The user explicitly accepted this revision.'};await save();
assert.equal((await run()).ready,true);
await put(source,'manual source edit');assert.equal((await run()).ready,false);
await assert.rejects(()=>run({initialize:true}),/export before review/);
await put(source,'editable source');await put(runtime,'different runtime');assert.equal((await run()).ready,false);
await put(runtime,'runtime geometry');await put(image,'overwritten screenshot');assert.equal((await run()).ready,false);
await put(image,'captured pixels');
record.evidence[0].path='../../outside.png';await save();assert.equal((await run()).ready,false);
record.evidence[0].path=image;await save();
await mkdir(path.join(root,'tools/asset-presentation'),{recursive:true});
const renderer='tools/asset-presentation/digital-resolve.js';
const lifecycleRenderer='tools/asset-presentation/lifecycle.js';await put(lifecycleRenderer,'lifecycle renderer');
await put(renderer,'renderer revision one');item.data.presentation={resolve:{type:'digital_blocks'}};
assert.equal((await run()).ready,false,'An unreviewed renderer must invalidate an effects review');
record.presentationFiles=[{path:renderer,sha256:hash(Buffer.from('renderer revision one'))},{path:lifecycleRenderer,sha256:hash(Buffer.from('lifecycle renderer'))}];await save();
assert.equal((await run()).ready,true);
await put(renderer,'renderer revision two');assert.equal((await run()).ready,false,'Renderer-only changes must invalidate review');
await put(renderer,'renderer revision one');assert.equal((await run()).ready,true);
item.data.presentation={lifecycle:{type:'blueprint'}};record.presentationFiles=record.presentationFiles.slice(1);await save();assert.equal((await run()).ready,true);
await put(lifecycleRenderer,'changed lifecycle renderer');assert.equal((await run()).ready,false);await put(lifecycleRenderer,'lifecycle renderer');
delete item.data.presentation;delete record.presentationFiles;await save();
await put(validation+'/report.json',{...identity,passed:false,errors:['Candidate failure']});assert.equal((await run()).ready,false);
await put(validation+'/report.json','null');assert.equal((await run()).ready,false);
await assert.rejects(()=>run({initialize:true}),/Technical validation/);
await put(validation+'/report.json',{...identity,revision:2,passed:true,errors:[]});item.data.revision=2;
assert.equal((await run()).ready,false,'Same bytes in a new revision still need a current record');
assert.equal((await run({initialize:true})).initialized,true);
assert.equal((await readdir(path.join(root,validation,'review_history'))).length,1);
record=JSON.parse(await readFile(path.join(root,validation,'visual_review.json'),'utf8'));
assert.equal(record.userAcceptance.status,'pending');assert.equal(record.secondPass.status,'pending');
